#
#   bash scripts/backup-to-r2.sh              # เธชเธณเธฃเธญเธเธเธเธ•เธด
#   bash scripts/backup-to-r2.sh --check      # เน€เธเนเธเธงเนเธฒเน€เธเธฃเธทเนเธญเธเธกเธทเธญ/เธ•เธฑเธงเนเธเธฃเธเธฃเธเนเธซเธก เนเธฅเนเธงเธญเธญเธ
#
# เธญเธญเธเนเธเธเนเธซเน "เธฅเนเธกเนเธฅเนเธงเธฃเธนเน" โ€” เธ—เธธเธเธเธฑเนเธเธ•เธฃเธงเธเธเธฅเธเธฃเธดเธ เนเธกเนเนเธเนเนเธเนเธเธฅเนเธญเธขเธเนเธฒเธ
# เน€เธเธฃเธฒเธฐ backup เธ—เธตเนเธฅเนเธกเน€เธเธตเธขเธเน เนเธขเนเธเธงเนเธฒเนเธกเนเธกเธต backup (เน€เธเธฃเธฒเธฐเน€เธฃเธฒเธเธดเธ”เธงเนเธฒเธกเธต)

set -Eeuo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${BACKUP_ENV_FILE:-$HERE/../.backup.env}"
[ -f "$ENV_FILE" ] && set -a && . "$ENV_FILE" && set +a

: "${SUPABASE_DB_URL:?เธ•เนเธญเธเธ•เธฑเนเธ SUPABASE_DB_URL (session pooler เธซเธฃเธทเธญ direct connection โ€” เธซเนเธฒเธกเนเธเน transaction pooler)}"
: "${R2_BUCKET:?เธ•เนเธญเธเธ•เธฑเนเธ R2_BUCKET}"
: "${R2_ENDPOINT:?เธ•เนเธญเธเธ•เธฑเนเธ R2_ENDPOINT เน€เธเนเธ https://<account_id>.r2.cloudflarestorage.com}"
: "${AWS_ACCESS_KEY_ID:?เธ•เนเธญเธเธ•เธฑเนเธ AWS_ACCESS_KEY_ID (R2 Access Key ID)}"
: "${AWS_SECRET_ACCESS_KEY:?เธ•เนเธญเธเธ•เธฑเนเธ AWS_SECRET_ACCESS_KEY (R2 Secret Access Key)}"
: "${BACKUP_AGE_RECIPIENT:?เธ•เนเธญเธเธ•เธฑเนเธ BACKUP_AGE_RECIPIENT (public key เธเธญเธ age) โ€” เธซเนเธฒเธกเธญเธฑเธเธเนเธญเธกเธนเธฅเธฅเธนเธเธเนเธฒเนเธเธเนเธกเนเน€เธเนเธฒเธฃเธซเธฑเธช}"

# R2 เนเธกเนเธกเธต region เธเธฃเธดเธเนเธ•เน aws cli เธเธฑเธเธเธฑเธเธ•เนเธญเธเธกเธต โ€” เนเธกเนเธ•เธฑเนเธเนเธฅเนเธงเธเธฐเธเนเธญเธ "You must specify a region"
export AWS_DEFAULT_REGION="${AWS_DEFAULT_REGION:-auto}"
# aws cli v2 เธ•เธฑเนเธเนเธ•เน 2.23 เนเธเธ CRC32 checksum เนเธเธ—เธธเธ request เธเธถเนเธ R2 เธเธเธดเน€เธชเธ (เธฅเนเธกเนเธเธ error เธเธเน)
# เธ•เธฑเธงเนเธเธฃเธเธตเนเธชเธฑเนเธเนเธซเนเนเธเธเน€เธเธเธฒเธฐเธ•เธญเธเธเธณเน€เธเนเธ โ€” v1 เนเธกเนเธฃเธนเนเธเธฑเธเธ•เธฑเธงเนเธเธฃเธเธตเน เนเธชเนเนเธงเนเธเนเนเธกเนเธกเธตเธเธฅเธเนเธฒเธเน€เธเธตเธขเธ
export AWS_REQUEST_CHECKSUM_CALCULATION="${AWS_REQUEST_CHECKSUM_CALCULATION:-when_required}"
export AWS_RESPONSE_CHECKSUM_VALIDATION="${AWS_RESPONSE_CHECKSUM_VALIDATION:-when_required}"

PG_IMAGE="${PG_IMAGE:-postgres:17-alpine}"
PREFIX="${R2_PREFIX:-minimalcnx}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
DAY="$(date -u +%Y-%m-%d)"
WORK="$(mktemp -d)"
DUMP="$WORK/minimalcnx-$STAMP.dump"
ENC="$DUMP.age"
KEY="$PREFIX/daily/$DAY/minimalcnx-$STAMP.dump.age"

log()  { printf '[%s] %s\n' "$(date -u +%H:%M:%SZ)" "$*"; }
send_alert() {
  local msg="$1"
  if [ -n "${BACKUP_ALERT_WEBHOOK:-}" ]; then
    curl -s -m 5 -X POST -H "Content-Type: application/json" \
      -d "{\"content\":\"[MinimalCNX Backup] $msg\"}" \
      "$BACKUP_ALERT_WEBHOOK" >/dev/null 2>&1 || true
  fi
}
fail() {
  local err="$*"
  printf '[%s] โ %s\n' "$(date -u +%H:%M:%SZ)" "$err" >&2
  send_alert "โ เธชเธณเธฃเธญเธเธเนเธญเธกเธนเธฅเธฅเนเธกเน€เธซเธฅเธง: $err"
  exit 1
}
trap 'rm -rf "$WORK"' EXIT
trap 'fail "เธฅเนเธกเน€เธซเธฅเธงเธ—เธตเนเธเธฃเธฃเธ—เธฑเธ” $LINENO"' ERR

need() { command -v "$1" >/dev/null 2>&1 || fail "เนเธกเนเธเธเธเธณเธชเธฑเนเธ $1 โ€” เธ”เธนเธงเธดเธเธตเธ•เธดเธ”เธ•เธฑเนเธเนเธ deploy/BACKUP.md"; }
need docker
need age
need aws

# transaction pooler (เธเธญเธฃเนเธ• 6543) เนเธเน pg_dump เนเธกเนเนเธ”เน โ€” เธกเธฑเธเธ•เนเธญเธเธเธฒเธฃ session state + snapshot
# เธ—เธตเนเธเธเธ—เธตเนเธ•เธฅเธญเธ”เธเธฒเธฃ dump เธเธถเนเธ transaction mode เนเธกเนเธฃเธฑเธเธเธฃเธฐเธเธฑเธเนเธซเน
case "$SUPABASE_DB_URL" in
  *:6543*) fail "SUPABASE_DB_URL เธเธตเนเนเธ transaction pooler (:6543) โ€” pg_dump เนเธเนเนเธกเนเนเธ”เน เธ•เนเธญเธเนเธเน session pooler (:5432) เธซเธฃเธทเธญ direct connection" ;;
esac

# psql/pg_dump เธ—เธตเนเนเธ”เนเธชเธ•เธฃเธดเธเธเธถเนเธเนเธกเนเนเธเน URI เธเธฐเธ•เธตเธเธงเธฒเธกเธงเนเธฒเน€เธเนเธ "เธเธทเนเธญเธเธฒเธเธเนเธญเธกเธนเธฅ" เนเธฅเนเธงเน€เธเธตเธขเธเน เนเธเธ•เนเธญ socket
# เนเธเน€เธเธฃเธทเนเธญเธเนเธ—เธ โ€” error เธ—เธตเนเนเธ”เนเธเธฐเธเธนเธ”เธ–เธถเธ /var/run/postgresql เธเธถเนเธเธเธงเธเนเธซเนเนเธฅเนเธเธดเธ”เธ—เธฒเธเนเธเนเธเธฅเธกเธฒเธ
case "$SUPABASE_DB_URL" in
  postgresql://*|postgres://*) : ;;
  *) fail "SUPABASE_DB_URL เธ•เนเธญเธเธเธถเนเธเธ•เนเธเธ”เนเธงเธข postgresql:// โ€” เธเธฑเธ”เธฅเธญเธเธกเธฒเธเธฒเธ Supabase โ’ Project Settings โ’ Database โ’ Connection string โ’ URI (เน€เธฅเธทเธญเธ Session pooler เธเธญเธฃเนเธ• 5432) เนเธฅเธฐเธ–เนเธฒเธฃเธซเธฑเธชเธเนเธฒเธเธกเธตเธญเธฑเธเธเธฃเธฐเธเธดเน€เธจเธฉเธญเธขเนเธฒเธ @ # ? / เธ•เนเธญเธ percent-encode เธเนเธญเธ" ;;
esac

if [ "${1:-}" = "--check" ]; then
  log "เน€เธเธฃเธทเนเธญเธเธกเธทเธญเธเธฃเธ เนเธฅเธฐเธ•เธฑเธงเนเธเธฃเธเธฃเธเธ—เธธเธเธ•เธฑเธง"
  log "เธ—เธ”เธชเธญเธเธ•เนเธญ Postgres..."
  docker run --rm -e PGCONNECT_TIMEOUT=15 "$PG_IMAGE" \
    psql "$SUPABASE_DB_URL" -tAc 'select current_database(), version();' \
    || fail "เธ•เนเธญเธเธฒเธเธเนเธญเธกเธนเธฅเนเธกเนเนเธ”เน โ€” เน€เธเนเธ SUPABASE_DB_URL"
  log "เธ—เธ”เธชเธญเธเน€เธเธตเธขเธ R2..."
  echo ok | aws s3 cp - "s3://$R2_BUCKET/$PREFIX/.healthcheck" --endpoint-url "$R2_ENDPOINT" >/dev/null \
    || fail "เน€เธเธตเธขเธ R2 เนเธกเนเนเธ”เน โ€” เน€เธเนเธ token/bucket/endpoint"
  log "โ… เธเธฃเนเธญเธกเนเธเนเธเธฒเธ"
  exit 0
fi

# โ”€โ”€ 1) dump โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€
# เนเธเน pg_dump เธเธฒเธ docker image เนเธซเน major version เธ•เธฃเธเธเธฑเธเน€เธเธดเธฃเนเธเน€เธงเธญเธฃเน โ€” pg_dump เธ—เธตเนเน€เธเนเธฒเธเธงเนเธฒ
# เน€เธเธดเธฃเนเธเน€เธงเธญเธฃเนเธเธฐเธเธเธดเน€เธชเธเธ—เธณเธเธฒเธเธ—เธฑเธเธ—เธต เนเธฅเธฐเธเธญเธเธ—เธตเนเธ•เธดเธ”เธกเธฒเธเธฑเธ VPS เธกเธฑเธเน€เธเนเธเธเธเธฅเธฐเน€เธงเธญเธฃเนเธเธฑเธ
# -Fc = custom format (เธเธตเธเธญเธฑเธ”เนเธเธ•เธฑเธง + restore เธ—เธตเธฅเธฐเธ•เธฒเธฃเธฒเธเนเธ”เน)
log "เธเธณเธฅเธฑเธ dump เธเธฒเธเธเนเธญเธกเธนเธฅ..."
docker run --rm -e PGCONNECT_TIMEOUT=30 -v "$WORK:/out" "$PG_IMAGE" \
  pg_dump "$SUPABASE_DB_URL" \
    --format=custom \
    --no-owner --no-privileges \
    --schema=public --schema=storage \
    --file="/out/$(basename "$DUMP")" \
  || fail "pg_dump เธฅเนเธกเน€เธซเธฅเธง"

[ -s "$DUMP" ] || fail "เนเธเธฅเน dump เธงเนเธฒเธเน€เธเธฅเนเธฒ"
SIZE=$(stat -c %s "$DUMP" 2>/dev/null || stat -f %z "$DUMP")
[ "$SIZE" -gt 20480 ] || fail "เนเธเธฅเน dump เน€เธฅเนเธเธเธดเธ”เธเธเธ•เธด ($SIZE bytes) โ€” เธเนเธฒเธเธฐ dump เนเธกเนเธเธฃเธ"
log "dump เธชเธณเน€เธฃเนเธ ($((SIZE / 1024)) KB)"

# โ”€โ”€ 2) เน€เธเนเธฒเธฃเธซเธฑเธช โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€
# เธเนเธฒเธเนเธเธกเธตเน€เธเธญเธฃเนเนเธ—เธฃเธฅเธนเธเธเนเธฒเธ—เธฑเนเธเธเธฒเธ + เน€เธฅเธเธเธฑเธ•เธฃเธเธฃเธฐเธเธฒเธเธ/เน€เธฅเธเธเธฑเธเธเธตเธเธเธฒเธเธฒเธฃเธเธเธฑเธเธเธฒเธ (business_config.emp_details)
# + เน€เธฅเธเธเธนเนเน€เธชเธตเธขเธ เธฒเธฉเธตเนเธ form50_payees โ€” เน€เธเนเธเธเนเธญเธกเธนเธฅเธชเนเธงเธเธเธธเธเธเธฅเธ•เธฒเธก PDPA เน€เธ•เนเธกเน เธซเนเธฒเธกเธงเธฒเธเธ”เธดเธเธเธ object storage
log "เธเธณเธฅเธฑเธเน€เธเนเธฒเธฃเธซเธฑเธช..."
age -r "$BACKUP_AGE_RECIPIENT" -o "$ENC" "$DUMP" || fail "เน€เธเนเธฒเธฃเธซเธฑเธชเธฅเนเธกเน€เธซเธฅเธง"
[ -s "$ENC" ] || fail "เนเธเธฅเนเธ—เธตเนเน€เธเนเธฒเธฃเธซเธฑเธชเธงเนเธฒเธเน€เธเธฅเนเธฒ"
rm -f "$DUMP"

# โ”€โ”€ 3) เธญเธฑเธเธเธถเนเธ R2 โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€
log "เธเธณเธฅเธฑเธเธญเธฑเธเนเธซเธฅเธ”เนเธ r2://$R2_BUCKET/$KEY ..."
aws s3 cp "$ENC" "s3://$R2_BUCKET/$KEY" \
  --endpoint-url "$R2_ENDPOINT" \
  --only-show-errors \
  || fail "เธญเธฑเธเนเธซเธฅเธ”เธฅเนเธกเน€เธซเธฅเธง"

# โ”€โ”€ 4) เธ•เธฃเธงเธเธงเนเธฒเนเธเธฅเนเธญเธขเธนเนเธเธฃเธดเธเนเธฅเธฐเธเธเธฒเธ”เธ•เธฃเธ โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€
# เนเธกเนเน€เธเธทเนเธญ exit code เธญเธขเนเธฒเธเน€เธ”เธตเธขเธง โ€” เธ–เธฒเธกเธเธฅเธฑเธเธงเนเธฒเนเธเธฅเนเธญเธขเธนเนเธเธ R2 เธเธฃเธดเธเนเธซเธกเนเธฅเธฐเธเธเธฒเธ”เน€เธ—เนเธฒเธเธฑเธเนเธซเธก
LOCAL_SIZE=$(stat -c %s "$ENC" 2>/dev/null || stat -f %z "$ENC")
REMOTE_SIZE=$(aws s3api head-object --bucket "$R2_BUCKET" --key "$KEY" \
  --endpoint-url "$R2_ENDPOINT" --query ContentLength --output text) \
  || fail "เธญเธฑเธเนเธซเธฅเธ”เนเธฅเนเธงเนเธ•เนเธซเธฒเนเธเธฅเนเธเธ R2 เนเธกเนเน€เธเธญ"
[ "$LOCAL_SIZE" = "$REMOTE_SIZE" ] \
  || fail "เธเธเธฒเธ”เนเธเธฅเนเธเธ R2 เนเธกเนเธ•เธฃเธเธเธฑเธเธ•เนเธเธ—เธฒเธ ($REMOTE_SIZE != $LOCAL_SIZE)"

# โ”€โ”€ 5) เธชเธณเน€เธเธฒเธฃเธฒเธขเน€เธ”เธทเธญเธ (เน€เธเนเธเธขเธฒเธง) โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€โ”€
# lifecycle rule เธเธญเธ R2 เธฅเธ daily/ เธ•เธฒเธกเธญเธฒเธขเธธ เนเธ•เน monthly/ เน€เธเนเธเนเธงเนเธขเธฒเธง โ€” เธงเธฑเธเธ—เธตเน 1 เธเธญเธเน€เธ”เธทเธญเธเธ—เธณเธชเธณเน€เธเธฒเน€เธเธดเนเธก
if [ "$(date -u +%d)" = "01" ]; then
  MKEY="$PREFIX/monthly/$(date -u +%Y-%m)/minimalcnx-$STAMP.dump.age"
  aws s3 cp "s3://$R2_BUCKET/$KEY" "s3://$R2_BUCKET/$MKEY" \
    --endpoint-url "$R2_ENDPOINT" --only-show-errors \
