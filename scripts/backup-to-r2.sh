#!/usr/bin/env bash
#
# backup-to-r2.sh โ€” เธชเธณเธฃเธญเธ Supabase Postgres เนเธ Cloudflare R2 (off-site, เน€เธเนเธฒเธฃเธซเธฑเธช)
